import { chromium } from 'playwright';
const NAMES = { "128ypj7": "dot", "1a6uo53": "dot-white", "5xjkw5": "none", okwo4e: "none", "1h57xtr": "view-project", afsa3o: "read-article", my4b76: "none" };
const [,, p, sel] = process.argv;
const browser = await chromium.launch({ channel: 'chrome' });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await page.goto('https://norda.framer.website' + p, { waitUntil: 'networkidle' });
const el = page.locator(sel).filter({ visible: true }).first();
await el.scrollIntoViewIfNeeded(); await page.waitForTimeout(600);
const b = await el.boundingBox();
const pts = [[b.x + 10, b.y + b.height / 2], [b.x + b.width / 2, b.y + b.height / 2], [b.x + b.width - 10, b.y + b.height / 2]];
console.log(await page.evaluate(([pts, NAMES]) => pts.map(([x, y]) => { const e = document.elementFromPoint(x, y); const c = e?.closest('[data-framer-cursor]'); const id = c?.getAttribute('data-framer-cursor') || 'okwo4e'; return `${Math.round(x)},${Math.round(y)} ${e?.tagName}.${e?.getAttribute('data-framer-name') || ''} → ${NAMES[id] || id}`; }).join(' | '), [pts, NAMES]));
await browser.close();
